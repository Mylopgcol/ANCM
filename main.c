void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim){
  if (htim->Instance == TIM2) {                 // se ejecuta a 8 kHz
    uint32_t t0 = DWT->CYCCNT;
    pil_step();
    uint32_t c = DWT->CYCCNT - t0;
    if (c > cyc_max) cyc_max = c;
    cyc_acc += c;  cyc_n++;  cyc_avg = cyc_acc / cyc_n;
    DAC->DHR12R1 = (uint32_t)(2048.0f + 1000.0f*pil_d_out);   // CH1 del osciloscopio: d(n)
    DAC->DHR12R2 = (uint32_t)(2048.0f + 1000.0f*pil_e_out);   // CH2: e(n)
  }
}
